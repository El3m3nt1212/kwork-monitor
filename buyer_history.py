# -*- coding: utf-8 -*-
"""
Досье покупателя по нашим же наблюдениям — пометка к оповещению.

Зачем. 2026-08-18 в бот пришёл заказ «доработать дашборд для Tilda, 1 000 ₽ за
оплачиваемый пилот» (ник покупателя здесь опущен). В базе монитора у него уже
лежало 15 заказов, размещённых одной пачкой 2026-08-12 (от 1 000 до 60 000 ₽,
от MVP краудфандинга до «найти автомеханика в Москве») — и **ни один из 15 не
закрылся досрочно**: все провисели до дедлайна. При фоне 35% это не невезение.

Что здесь НЕ реализовано и почему. Первой гипотезой было текстовое правило —
«пачка несвязанных задач под одну минимальную цену со словом „пилот“». Проверка
по базе (`research/kwork/buyer_track_record.py`) её похоронила: заказы из пачек
закрываются досрочно ЧАЩЕ фона (41% против 35%), единая цена на пачку не
отличается от фона вовсе, а слово «пилот» встретилось 5 раз на 6 539 заказов —
описания в ленте обрезаны, монитор его почти не видит. Работает не текст, а
собственная история наблюдений: у покупателей, чья первая половина заказов
прошла без единого досрочного закрытия, во второй половине досрочных 15%
против 47% у остальных.

Порог MIN_OUTCOMES=5 — не статистика, а здравый смысл: на трёх заказах «ни
одного досрочного» бывает у кого угодно.

Заказ не отсеивается, а помечается. Прокси грубый (снятие модерацией и отмена
покупателем неотличимы от найма), а коннект в конце концов тратит человек.
"""
from __future__ import annotations

import sqlite3

# Ниже этого числа известных исходов досье покупателя ничего не значит.
MIN_OUTCOMES = 5

# Исходы, по которым вообще можно судить (см. storage.classify_gone).
_DONE = ("early", "early_mass", "timeout")
_HIRED = ("early", "early_mass")


def record(conn: sqlite3.Connection, buyer: str | None) -> tuple[int, int]:
    """(сколько заказов покупателя мы досмотрели до конца, сколько из них ушло досрочно)."""
    if not buyer:
        return 0, 0
    row = conn.execute(
        f"""SELECT COUNT(*),
                   SUM(CASE WHEN gone_reason IN {_HIRED} THEN 1 ELSE 0 END)
            FROM orders
            WHERE buyer_username = ? AND gone_reason IN {_DONE}""", (buyer,)).fetchone()
    return (row[0] or 0), (row[1] or 0)


def note(conn: sqlite3.Connection, buyer: str | None) -> str | None:
    """Строка для оповещения. None — истории мало, сказать нечего."""
    seen, early = record(conn, buyer)
    if seen < MIN_OUTCOMES:
        return None
    if early == 0:
        return (f"⚠ видели {seen} его заказов — ни один не закрылся досрочно "
                f"(фон 35%): похоже, не нанимает вообще")
    return f"видели {seen} его заказов, досрочно закрылись {early}"
