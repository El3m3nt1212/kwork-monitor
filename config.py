from pathlib import Path

MONITOR_DIR = Path(__file__).resolve().parent
# В исходном проекте монитор лежал внутри папки исследования, и данные писались
# уровнем выше. В отдельном репозитории всё живёт рядом с кодом.
KWORK_DIR = MONITOR_DIR
PROFILE_DIR = MONITOR_DIR / ".browser_profile"
DB_PATH = KWORK_DIR / "data" / "kwork_monitor.db"

BASE_URL = "https://kwork.ru"
PROJECTS_URL = f"{BASE_URL}/projects"

# Лента всей биржи. Без `c=all` страница показывает только рубрики, отмеченные
# у аккаунта как «любимые» (проверено 2026-07-25: 54 проекта против 492) —
# то есть монитор без этого параметра видит биржу через щель.
FEED_URL = f"{PROJECTS_URL}?c=all"

# Предохранитель обхода: если пагинация вдруг сообщит неправдоподобное число
# страниц, дальше этого всё равно не пойдём.
FEED_MAX_PAGES = 80

# Полный обход всех страниц — дорогая операция (~42 запроса). Между полными
# обходами делается лёгкий проход по первым страницам: он ловит новые проекты
# и обновляет наблюдения, но никого не хоронит (см. storage.record_run).
FULL_SWEEP_MIN_INTERVAL_SEC = 55 * 60
LIGHT_SWEEP_PAGES = 3

# Пауза между запросами страниц ленты. 2.5 с на 44 страницы подряд оказалось
# заметно для площадки — на 17-й странице выдача начала приходить пустой,
# хотя та же страница поодиночке открывалась нормально.
FEED_PAGE_DELAY_SEC = 4.0

# Повторы одной страницы при пустой/недогруженной выдаче и пауза между ними.
FEED_PAGE_ATTEMPTS = 3
FEED_RETRY_BACKOFF_SEC = 8.0

# Ключевые слова для обхода биржи заказов. Список стартует с того же набора,
# что уже используется в ежедневной ручной проверке (см. карточку
# ideas/candidates/2026-07-21_ru-freelance-automation.md), расширять по ходу.
KEYWORDS = [
    "парсинг",
    "telegram бот",
    "автоматизация",
    "превью",
    "оверлей",
    "оформление стрима",
    "дизайн канала",
]

# Пауза между запросами разных ключевых слов внутри одного прохода (сек).
# Не агрессивно — нет смысла долбить сервер быстрее, чем можно вычитать
# страницу глазами; риск детекта нас не пугает, но и провоцировать его
# бессмысленной скоростью незачем.
