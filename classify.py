"""Отделение лидогенерации от нормальных задач в ленте проектов.

Зачем. Фильтр «мало предложений» сам по себе не отбирает возможности: верх
списка «большой бюджет + пусто» занят не недооценёнными техническими задачами,
а предложениями приводить клиентов. Там пусто по той же причине, по которой
пусто в любой партнёрке, и большие цифры бюджета — это не оплата работы, а
потолок комиссии с продаж.

Как отличаем. Не перечислением фраз (их бесконечно много: «поиск клиентов»,
«привлечение новых клиентов», «найти 10 клиентов»…), а сочетанием двух вещей
рядом: **глагол получения** (поиск, найти, привлечь, куплю, нужны, плачу за) и
**объект** (клиент, лид, заявка, покупатель, продажи). Это и есть просьба
отдать клиентов, а не сделанную работу.

Две ловушки, из-за которых наивные правила врут в обе стороны:

1. «Разработать бота для сбора лидов» — слово «лиды» есть, но заказ нормальный.
   Спасает то, что «сбор» не глагол получения: пара не складывается.
2. «Настроить рекламу для привлечения клиентов» — пара складывается, но это
   обычный заказ на настройку рекламы, а привлечение клиентов тут цель
   заказчика, а не предмет заказа. Спасает **порядок слов**: если работа названа
   раньше, чем клиенты, — это заказ на работу. Если клиенты названы первыми
   («Поиск клиентов на разработку сайтов») — это лидогенерация, несмотря на
   слово «разработка» в том же заголовке.
"""
from __future__ import annotations

import re

# Глаголы и обороты «дайте мне».
ACQUIRE = (
    r"поиск\w*|искать|ищу|найти|найд\w+|находить|привлеч\w+|привлекать|"
    r"привлечени\w*|привести|приводить|приведённ\w+|приведенн\w+|"
    r"купл\w+|покупа\w+|плачу\s+за|нужн\w+|необходим\w+|требуют?ся|"
    r"генерац\w*|трафик"
)

# То, что просят отдать. Отдельно выписаны формы с беглой гласной: у «заявки»
# родительный падеж множественного — «заявок», и шаблон `заявк\w*` его не ловит.
# На этом теряется целый класс заголовков вида «Поиск заявок».
OBJECT = (
    r"клиент\w*|лид\w*|заявк\w*|заявок|заказчик\w*|покупател\w*|продаж\w*|"
    r"заказ\w*|сделк\w*|сделок"
)

# Между глаголом и объектом допускаем до трёх слов: «привлечение новых
# клиентов», «найти 10 клиентов на услугу».
_PAIR = re.compile(rf"\b({ACQUIRE})\b(?:\W+\w+){{0,3}}\W+\b({OBJECT})\b", re.I)
_PAIR_REV = re.compile(rf"\b({OBJECT})\b(?:\W+\w+){{0,2}}\W+\b({ACQUIRE})\b", re.I)

# Однозначные маркеры, которым пара не нужна.
STANDALONE = [
    r"лидогенерац\w*", r"квал\w*\s+лид", r"холодн\w*\s+(звонк|базу|обзвон)",
    r"обзвон\w*", r"прозвон\w*", r"партнёрк\w*|партнерк\w*", r"реферальн\w*\s+программ",
    r"млм", r"сетевой\s+маркетинг", r"продажник\w*", r"менеджер\w*\s+по\s+продажам",
    r"процент\w*\s+с\s+продаж", r"%\s*с\s+продаж", r"%\s*от\s+сделк",
    r"комисси\w*\s+с\s+продаж", r"за\s+привед[её]нн\w+",
    r"зарабатыва\w*\s+на\s+свои\w*\s+связ", r"канал\w*\s+продаж",
]
_STANDALONE = [re.compile(p, re.I) for p in STANDALONE]

# Слова, означающие «сделай работу». Гасят срабатывание, только если стоят в
# заголовке РАНЬШЕ упоминания клиентов (см. ловушку 2 в докстринге).
BUILD = re.compile(
    r"\b(разработ\w*|разработка|сдела\w+|создат\w+|создани\w+|написа\w+|"
    r"настро\w+|доработ\w+|сверста\w+|в[её]рстк\w*|интеграци\w*|внедрен\w*|"
    r"парсер\w*|парсинг\w*|скрипт\w*|макет\w*|дизайн\w*|перенест\w+|"
    r"починит\w*|исправит\w*|монтаж\w*|нарисова\w+|смонтирова\w+|"
    r"протестирова\w+|тестирован\w*|консультаци\w*|обучени\w*)\b",
    re.I,
)


# Заголовок-объявление без всякого глагола: «Лиды по Дубаи», «Клиенты для
# event-продукта», «Горячие заявки на IT услуги». Слово «продажи» сюда
# намеренно не входит — «Продажа готового сайта» слишком часто означает обычную
# сделку, а не лидогенерацию.
#
# Перед существительным допускается только прилагательное (по окончанию): иначе
# правило ловит «Форма заявки на сайте не отправляется», где «заявки» —
# зависимое слово, а заголовок вообще про сломанную форму.
# Формы существительных перечислены явно, а не через `клиент\w*`: иначе правило
# срабатывает на прилагательном — «Клиентская база для CRM».
_ADJ = r"\w+(?:ый|ий|ой|ая|яя|ое|ее|ые|ие|ых|их|ым|им|ыми|ими)"
_NOUN = r"лиды|лид|лидов|клиенты|клиент|клиентов|заявки|заявка|заявок"
_BARE_OFFER = re.compile(rf"^\s*(?:{_ADJ}\s+)?({_NOUN})\b", re.I)


def _lead_match(text: str):
    """Возвращает позицию первого срабатывания и что именно сработало."""
    best = None
    for rx in _STANDALONE:
        m = rx.search(text)
        if m and (best is None or m.start() < best[0]):
            best = (m.start(), m.group(0))
    for rx in (_PAIR, _PAIR_REV):
        m = rx.search(text)
        if m and (best is None or m.start() < best[0]):
            best = (m.start(), m.group(0))
    if best is None:
        m = _BARE_OFFER.match(text)
        if m:
            best = (m.start(1), m.group(0).strip())
    return best


# Классы заказов, закрытые не отсутствием навыка, а конкретным блокером из
# profile/constraints.md (пункт от 2026-08-03). Порядок важен: проверяется
# сверху вниз, первое совпадение и есть причина.
BLOCKERS = [
    ("проектирование: нужен CAD и подпись под нормами",
     r"\bАС\b|\bКР\b|\bАР\b|\bКМ\b|\bКД\b|\bТХ\b|\bПБ\b|\bПТ\b|\bНВК\b|КМД|ЭОМ|ОВ\+?АОВ|НВФ|УКЦ|"
     r"ростверк|фахверк|перекрыт|фундамент|молниезащит|пожаротуш|пожарн\w+\s+водопровод|вентиляц|"
     r"смет|СНиП|BIM|ЦИМ|статическ\w+\s+расч|прочност|навес|павильон|перегородк|благоустройств|"
     r"реконструкц|проект\s+(дома|виллы|ремонта|отоплен)|перевооружен|штамп\s+вырубн|стропильн|"
     r"обвязк\w+\s+парогенератор|разводк\w+\s+электрик|Solidworks|SketchUp|Базис|БАЗИС|"
     r"инженери\w*|документаци\w+\s+для\s+(строительств|изготовлен)|модульн\w+\s+дом|"
     r"аудит\s+проект"),
    ("накрутка и чужие аккаунты: заработанное конфискуют вместе с аккаунтом",
     r"отметк\w+\s+пользовател|упоминани|инвайт|масслукинг|накрутк|поведенческ|\bПФ\b|ботами|"
     r"закупка\s+ссылок|обратные\s+ссылки|ссылочн|траст\w*\s+ресурс|барахолк|постинг\s+по\s+форум|"
     r"вернуть\s+(ютуб|youtube)|удаление\s+архивн|покупка\s+действующего|"
     r"больше\s+подписчик|подписчик\w+\s+в\b|привлечени\w+\s+владельц"),
    ("покупка актива, а не заказ на работу",
     r"^\s*(купл[юё]|покупка|приобрет|рассмотрю\s+вариант\s+покупк)"),
    ("нужно физическое присутствие или оборудование",
     r"mocap|мокап\w*\s+костюм|костюме|монтаж\s+кондиционер|оклейк|курьер|насосн|"
     r"плат[уы]\s+под|прототип|металлокаркас|видеосъ[её]мк|съемка\s+видео|штанц"),
    ("MAX — личное неприятие пользователя",
     r"\bMAX\b|мессенджер\s+макс|в\s+максе"),
]
_BLOCKERS = [(name, re.compile(p, re.I)) for name, p in BLOCKERS]


def blocked_reason(title: str | None, description: str | None = None) -> str | None:
    """Что мешает взять этот заказ, если мешает. None — ничего из известного.

    Проверяется по заголовку: описание слишком часто упоминает смежные вещи
    («сайт для строительной компании» — не проектирование).
    """
    text = (title or "")
    if classify(text, description)[0]:
        return "лидогенерация: просят привести клиентов, а не сделать работу"
    for name, rx in _BLOCKERS:
        if rx.search(text):
            return name
    return None


def classify(title: str | None, description: str | None = None) -> tuple[bool, str]:
    """Возвращает (это_лидогенерация, что сработало).

    Решение принимается по заголовку: в описании нормальной задачи «чтобы
    привлекать клиентов» встречается сплошь и рядом как объяснение цели.
    Описание используется только чтобы поддержать слабый случай, когда в
    заголовке сработал одиночный маркер без пары.
    """
    title = (title or "").strip()
    if not title:
        return False, ""

    hit = _lead_match(title)
    if not hit:
        return False, ""

    pos, matched = hit
    build = BUILD.search(title)
    if build and build.start() < pos:
        # Работа названа раньше клиентов — это заказ на работу.
        return False, ""

    return True, matched
